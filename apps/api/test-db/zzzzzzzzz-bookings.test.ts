import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import test,{after} from 'node:test';
import {setTimeout} from 'node:timers/promises';
import {PrismaClient} from '@prisma/client';
import {postLedger} from '../src/ledger/service.js';
import {publishBookingPolicy} from '../src/bookings/settings.js';
import {createBooking,cancelBooking,issueBookingQr,scanBooking,listBookings,decideBooking,expireScheduledBooking} from '../src/bookings/service.js';
import {hashToken} from '../src/auth/sessions.js';
const url=new URL(process.env.DATABASE_URL??'');
if(!['localhost','127.0.0.1'].includes(url.hostname)||!/^\/(gym_ci|gym_test)$/.test(url.pathname))throw new Error('Disposable local test database required');
const db=new PrismaClient();after(()=>db.$disconnect());
test('scheduled escrow, refunds, physical QR arrival, no-shows and review permissions',async()=>{
 const user=(role:'PLATFORM_ADMIN'|'TRAINEE'|'GYM_OWNER')=>db.user.create({data:{role,displayName:'Synthetic booking user',phoneE164:'+20booking'+randomUUID()}});
 const admin=await user('PLATFORM_ADMIN'),customer=await user('TRAINEE'),other=await user('TRAINEE'),owner=await user('GYM_OWNER');
 const gym=await db.gym.create({data:{name:'Booking test gym',ownerId:owner.id,ownerAcceptedAt:new Date(),status:'ACTIVE'}});
 const branch=await db.branch.create({data:{gymId:gym.id,name:'Booking test branch',status:'ACTIVE',visitPricePoints:25,sessionMinutes:120,pricingVersion:1,priceApprovedAt:new Date()}});
 let pricing=await db.pricingPolicy.findFirst({orderBy:{version:'desc'}});
 if(!pricing)pricing=await db.pricingPolicy.create({data:{version:1,pointPricePiasters:100n,redemptionBps:8000,createdById:admin.id}});
 const issuance=await db.pointAccount.findFirst({where:{type:'ISSUANCE'}})??await db.pointAccount.create({data:{type:'ISSUANCE'}});
 const wallet=await db.pointAccount.create({data:{type:'TRAINEE_WALLET',ownerUserId:customer.id,expiresAt:new Date(Date.now()+86400000)}});
 await postLedger(db,{actorId:admin.id,idempotencyKey:randomUUID(),reason:'Synthetic booking funding',points:{kind:'ISSUE',entries:[{accountId:issuance.id,delta:-500n},{accountId:wallet.id,delta:500n}]}});
 const current=await db.bookingPolicy.findFirst({orderBy:{version:'desc'}});
 const p=await publishBookingPolicy(db,admin.id,{expectedVersion:current?.version??0,policy:{graceMinutes:60,mode:'MANUAL'}});
 const input={branchId:branch.id,scheduledAt:new Date(Date.now()+3600000).toISOString(),policyVersion:p.version,branchPricingVersion:1};
 const key=randomUUID(),b=await createBooking(db,customer.id,key,input);
 assert.equal((await createBooking(db,customer.id,key,input)).id,b.id);
 assert.equal((await db.pointAccount.findUniqueOrThrow({where:{id:wallet.id}})).balance,475);
 assert.equal((await db.moneyAccount.findFirst({where:{type:'GYM_AVAILABLE',gymId:gym.id}}))?.balancePiasters??0n,0n);
 await assert.rejects(createBooking(db,customer.id,key,{...input,scheduledAt:new Date(Date.now()+7200000).toISOString()}));
 await assert.rejects(cancelBooking(db,other.id,b.id,{reason:'Not my booking'}));
 assert.equal(await expireScheduledBooking(db,b.id),b.deadlineAt.toISOString());
 assert.equal((await db.booking.findUniqueOrThrow({where:{id:b.id}})).status,'RESERVED');
 await cancelBooking(db,customer.id,b.id,{reason:'Cannot attend'});
 assert.equal((await db.pointAccount.findUniqueOrThrow({where:{id:wallet.id}})).balance,500);
 await cancelBooking(db,customer.id,b.id,{reason:'Retry cancellation'});
 assert.equal((await db.pointAccount.findUniqueOrThrow({where:{id:wallet.id}})).balance,500);
 // Confirm early arrival while the immutable appointment remains one hour in the future.
 const bearer=randomUUID();
 await db.authSession.create({data:{userId:customer.id,tokenHash:hashToken(bearer),expiresAt:new Date(Date.now()+3600000)}});
 const arrival=await createBooking(db,customer.id,randomUUID(),{...input,scheduledAt:new Date(Date.now()+3600000).toISOString()});
 const qr=await issueBookingQr(db,customer.id,arrival.id,bearer);
 await assert.rejects(scanBooking(db,other.id,branch.id,{token:qr.token}));
 const scans=await Promise.allSettled([scanBooking(db,owner.id,branch.id,{token:qr.token}),scanBooking(db,owner.id,branch.id,{token:qr.token})]);
 assert.equal(scans.filter(x=>x.status==='fulfilled').length,1);
 const attended=await db.booking.findUniqueOrThrow({where:{id:arrival.id}});
 assert.equal(attended.status,'ATTENDED');assert.ok(attended.visitId);
 assert.equal(attended.scheduledAt.toISOString(),arrival.scheduledAt.toISOString());
 assert.ok((await db.visit.findUniqueOrThrow({where:{id:attended.visitId!}})).startedAt<attended.scheduledAt);
 assert.equal((await db.pointAccount.findUniqueOrThrow({where:{id:wallet.id}})).balance,475);
 assert.equal(await db.visit.count({where:{id:attended.visitId!}}),1);
 const activePolicy=await db.bookingPolicy.findFirstOrThrow({orderBy:{version:'desc'}});
 const manual=await publishBookingPolicy(db,admin.id,{expectedVersion:activePolicy.version,policy:{graceMinutes:0,mode:'MANUAL'}});
 const missed=await createBooking(db,customer.id,randomUUID(),{...input,policyVersion:manual.version,scheduledAt:new Date(Date.now()+250).toISOString()});
 await setTimeout(300);
 await expireScheduledBooking(db,missed.id);
 assert.equal((await db.booking.findUniqueOrThrow({where:{id:missed.id}})).status,'PENDING_REVIEW');
 await cancelBooking(db,customer.id,missed.id,{reason:'Transport problem'});
 await assert.rejects(decideBooking(db,owner.id,missed.id,{reason:'Unauthorized decision',allocation:{traineeBps:10000,gymBps:0,platformBps:0}}));
 const result=await decideBooking(db,admin.id,missed.id,{reason:'Reviewed transport problem',allocation:{traineeBps:5000,gymBps:5000,platformBps:0}});
 assert.equal(result.traineePoints!+result.gymPoints!,25);
 assert.equal(result.traineePoints,13);
 await assert.rejects(decideBooking(db,admin.id,missed.id,{reason:'Second decision',allocation:{traineeBps:10000,gymBps:0,platformBps:0}}));
 const auto=await publishBookingPolicy(db,admin.id,{expectedVersion:manual.version,policy:{graceMinutes:0,mode:'AUTOMATIC',allocation:{traineeBps:0,gymBps:5000,platformBps:5000}}});
 const automated=await createBooking(db,customer.id,randomUUID(),{...input,policyVersion:auto.version,scheduledAt:new Date(Date.now()+250).toISOString()});
 await setTimeout(300);await Promise.all([expireScheduledBooking(db,automated.id),expireScheduledBooking(db,automated.id)]);
 const resolved=await db.booking.findUniqueOrThrow({where:{id:automated.id}});
 assert.equal(resolved.status,'RESOLVED');
 assert.equal(resolved.gymPoints!+resolved.platformPoints!,25);
 assert.equal(resolved.traineePoints,0);
 assert.equal(await db.pointTransaction.count({where:{idempotencyKey:'booking-resolution:'+automated.id}}),1);
 await expireScheduledBooking(db,automated.id);
 assert.equal(await db.pointTransaction.count({where:{idempotencyKey:'booking-resolution:'+automated.id}}),1);
 assert.equal((await db.pointAccount.findUniqueOrThrow({where:{type_ownerUserId:{type:'BOOKING_HOLD',ownerUserId:customer.id}}})).balance,0);
});
