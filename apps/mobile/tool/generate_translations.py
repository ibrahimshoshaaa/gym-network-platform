"""Generate the typed Dart catalog from reviewed ARB files. No network needed."""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]/'lib'/'l10n'
def generate():
 catalogs={lang:json.loads((ROOT/f'app_{lang}.arb').read_text()) for lang in ('ar','en')}
 keys=[k for k in catalogs['ar'] if not k.startswith('@')]
 assert set(keys)=={k for k in catalogs['en'] if not k.startswith('@')},'Locale key coverage differs'
 for key in keys:
  assert re.findall(r'\{p\d+\}',catalogs['ar'][key])==re.findall(r'\{p\d+\}',catalogs['en'][key]),f'Placeholder mismatch: {key}'
  assert not re.search('[\u0600-\u06ff]',catalogs['en'][key]) or catalogs['en'][key]=='العربية',f'Untranslated English string: {key}'
 for source in (ROOT.parent).rglob('*.dart'):
  if source.name == 'catalog.g.dart':continue
  for match in re.finditer(r'''appText\(['"](s\d+)['"]''',source.read_text()):
   assert match[1] in keys,f'Unknown catalog key in {source}: {match[1]}'
 output=['// Generated by tool/generate_translations.py. Edit the ARB sources.']
 for lang,c in catalogs.items():
  output.append(f'const {lang}Catalog = <String, String>{{')
  for k in keys:
   literal=json.dumps(c[k],ensure_ascii=False).replace('$',r'\$')
   output.append(f'  {json.dumps(k)}: {literal},')
  output.append('};')
 return '\n'.join(output)+'\n'
if __name__=='__main__':
 import sys
 result=generate();target=ROOT/'catalog.g.dart'
 if '--check' in sys.argv:assert target.read_text()==result,'Regenerate the Dart catalog'
 else:target.write_text(result)
 print('Translation catalogs verified')
